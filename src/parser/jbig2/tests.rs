#[test]
fn generic_region_mmr() {
    let (w, h, buf) = decode_stream(&MMR_STREAM);
    assert_eq!((w, h), (16, 4));
    assert_eq!(buf, MMR_EXPECT);
}

#[test]
fn generic_region_mmr_error_truncated() {
    // Truncated MMR stream must error, not panic (R1).
    let cut = &MMR_STREAM[..MMR_STREAM.len() - 3];
    let r = decode(cut, None);
    // Missing rows pad with zeros in the reference; accept Ok or Err
    // but never panic.
    let _ = r;
}

#[test]
fn symbol_dictionary_arithmetic() {
    let (w, h, buf) = decode_stream(&ARITH_STREAM);
    assert_eq!((w, h), (132, 14));
    assert_eq!(buf, ARITH_EXPECT);
}

#[test]
fn pattern_dictionary_halftone_mmr() {
    let (w, h, buf) = decode_stream(&HALFTONE_STREAM);
    assert_eq!((w, h), (16, 16));
    assert_eq!(buf, HALFTONE_EXPECT);
}

#[test]
fn globals_stream_sharing() {
    // Fixture 2 has no globals; feeding an empty globals chunk must
    // still decode identically (globals segments are just prepended).
    let (w, h, buf) = decode(&ARITH_STREAM, Some(&[])).expect("decode with empty globals");
    assert_eq!((w, h), (132, 14));
    assert_eq!(buf, ARITH_EXPECT);
}

#[test]
fn invalid_segment_type_rejected() {
    let mut bad = MMR_STREAM.clone();
    bad[4] = 0x05; // invalid segment type in flags byte
    assert!(decode(&bad, None).is_err());
}

#[test]
fn empty_stream_errors() {
    assert!(decode(&[], None).is_err());
}
