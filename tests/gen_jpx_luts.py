#!/usr/bin/env python3
"""Generate src/parser/jpx/t1_luts.rs from OpenJPEG 1.5.2 headers (port authority)."""
import re

luts_h = open('/tmp/opencode/t1_15_luts.h').read()
mqc_c = open('/tmp/opencode/mqc.c').read()  # 2.x master, same table as 1.5.2

def parse_array(text, name, count, base=10):
    m = re.search(re.escape(name) + r"\[[^\]]*\]\s*=\s*\{(.*?)\};", text, re.S)
    body = m.group(1)
    vals = []
    for tok in re.findall(r"0[xX][0-9a-fA-F]+|\d+", body):
        vals.append(int(tok, 16) if tok.lower().startswith('0x') else int(tok))
    assert len(vals) == count, (name, len(vals), count)
    return vals

zc = parse_array(luts_h, "static char lut_ctxno_zc", 1024)
sc = parse_array(luts_h, "static char lut_ctxno_sc", 256)
spb = parse_array(luts_h, "static char lut_spb", 256)

# MQ state table: {qe, mps, nmps, nlps} x 94
m = re.search(r"mqc_states\[47 \* 2\]\s*=\s*\{(.*?)\};", mqc_c, re.S)
entries = []
for tok in re.findall(r"\{\s*0x([0-9a-fA-F]+),\s*(\d),\s*&mqc_states\[(\d+)\],\s*&mqc_states\[(\d+)\]\s*\}", m.group(1)):
    qe, mps, nmps, nlps = int(tok[0], 16), int(tok[1]), int(tok[2]), int(tok[3])
    entries.append((qe, mps, nmps, nlps))
assert len(entries) == 94, len(entries)

def fmt_arr(vals, per_line, ty):
    lines = []
    for i in range(0, len(vals), per_line):
        lines.append("    " + ", ".join(str(v) for v in vals[i:i+per_line]) + ",")
    return ty + " [\n" + "\n".join(lines) + "\n];\n"

out = []
out.append("""//! T1/MQ lookup tables ported from OpenJPEG 1.5.2 (`t1_luts.h`) and the MQ
//! state table (`mqc.c`, 94 entries = 47 probability states x 2 MPS values).
//! Generated by `tools/gen_jpx_luts.py` — do not edit by hand.

#![allow(clippy::all)]

/// MQ probability-state table: `state[i] = (qe, mps, nmps, nlps)` where
/// nmps/nlps are absolute indices into this array.
""")
out.append("pub static MQC_STATES: [(u16, u8, u8, u8); 94] = [\n")
for qe, mps, nmps, nlps in entries:
    out.append(f"    (0x{qe:04x}, {mps}, {nmps}, {nlps}),\n")
out.append("];\n\n")

out.append("""/// Zero-coding context LUT: index `(orient << 8) | (flags & T1_SIG_OTH)`.
/// `orient` = band number 0(LL), 1(HL), 2(LH), 3(HH).
""")
out.append(fmt_arr(zc, 32, "pub static LUT_CTXNO_ZC: [u8; 1024] ="))
out.append("\n/// Sign-coding context LUT: index `(flags & (SIG_PRIM | SGN)) >> 4`.\n")
out.append(fmt_arr(sc, 32, "pub static LUT_CTXNO_SC: [u8; 256] ="))
out.append("\n/// Sign prediction bit LUT: index `(flags & (SIG_PRIM | SGN)) >> 4`.\n")
out.append(fmt_arr(spb, 32, "pub static LUT_SPB: [u8; 256] ="))

open('pdf-editor-rust-core/src/parser/jpx/t1_luts.rs', 'w').write(''.join(out))
print("generated", len(out), "lines-ish")
